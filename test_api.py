class _MockLLMHandler(BaseHTTPRequestHandler):
    """A tiny OpenAI-compatible /chat/completions mock."""

    def do_POST(self):
        length = int(self.headers.get("Content-Length", 0))
        payload = json.loads(self.rfile.read(length).decode())
        system = payload["messages"][0]["content"]
        if "PER-TOPIC ASSESSMENT" in system:
            content = json.dumps({
                "summary": "Mock summary: solid fundamentals with a couple of gaps to close.",
                "strengths": ["Mock strength: retrieval explained clearly.", "Mock strength: agents."],
                "gaps": ["Mock gap: deployment depth."],
                "next": ["Mock next: rebuild the router.", "Mock next: practice MCP.", "Mock next: mock interview."],
            })
        else:
            content = json.dumps({
                "text": "MOCK-LLM: let's dig one level deeper on that.",
                "action": "followup",
                "assessment": "solid",
            })
        body = json.dumps({"choices": [{"message": {"content": content}}]}).encode()
        self.send_response(200)
        self.send_header("Content-Type", "application/json")
        self.send_header("Content-Length", str(len(body)))
        self.end_headers()
        self.wfile.write(body)

    def log_message(self, *args):  # silence
        pass


RICH_BLANKET = (
    "We used embeddings and retrieval with Chroma, grounded RAG, function calling with Pydantic, "
    "agents with tools and MCP servers, docker and kubernetes deployment, and prometheus monitoring."
)


def test_empty_candidate_edge() -> None:
    """A candidate with no mission record must not crash the service."""
    print("\n[4] Edge: candidate with no missions")
    curriculum = load_curriculum()
    ghost = {"member": {"id": "CAND-000", "name": "Ghost User", "jobRole": "N/A"},
             "missions": [], "signals": {}}
    session = InterviewSession("ghost", ghost, curriculum, llm=None)
    reply = session.start()
    check("empty candidate starts without crashing", isinstance(reply, str) and len(reply) > 20)
    fb = None
    for _ in range(40):
        reply, done, feedback = session.handle(
            "I built a chatbot that used embeddings, retrieval, and a grounded LLM prompt.")
        if done:
            fb = feedback
            break
    check("empty candidate completes with feedback", fb is not None and fb["gaps"])


def test_llm_path_and_fallback() -> None:
    print("\n[3] LLM path (mock OpenAI-compatible server) + fallback")
    from interview_agent.llm import LLMClient

    curriculum = load_curriculum()
    candidate = load_candidates()[0]

    mock = ThreadingHTTPServer(("127.0.0.1", 0), _MockLLMHandler)
    mock_port = mock.server_address[1]
    thread = threading.Thread(target=mock.serve_forever, daemon=True)
    thread.start()
    try:
        llm = LLMClient(base_url=f"http://127.0.0.1:{mock_port}", model="mock-model")
        session = InterviewSession("llm-test", candidate, curriculum, llm)
        session.start()
        replies: List[str] = []
        fb: Optional[Dict[str, Any]] = None
        for _ in range(50):
            reply, done, feedback = session.handle(RICH_BLANKET)
            replies.append(reply)
            if done:
                fb = feedback
                break
        check("LLM interview completes", fb is not None)
        check("LLM text used in replies", any("MOCK-LLM" in r for r in replies))
        check("LLM feedback used", fb is not None and fb["summary"].startswith("Mock summary"),
              json.dumps(fb))

        # Graceful fallback: point at a dead port, the interview must still complete.
        dead_llm = LLMClient(base_url="http://127.0.0.1:1", model="ghost", timeout=2)
        session2 = InterviewSession("fallback-test", candidate, curriculum, dead_llm)
        session2.start()
        fb2: Optional[Dict[str, Any]] = None
        for _ in range(50):
            reply, done, feedback = session2.handle(RICH_BLANKET)
            if done:
                fb2 = feedback
                break
        check("dead LLM falls back to deterministic engine and completes",
              fb2 is not None and fb2["summary"] and fb2["gaps"])
    finally:
        mock.shutdown()
        mock.server_close()


def main() -> None:
    test_planner_compliance()

    print("\n[4] Starting server for API contract tests…")
    env = dict(os.environ)
    proc = subprocess.Popen(
        [sys.executable, "-m", "uvicorn", "main:app", "--host", "127.0.0.1",
         "--port", str(PORT), "--log-level", "warning"],
        cwd=ROOT, env=env,
        stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL,
    )
    try:
        if not wait_for_server(proc):
            print("  ✘ server failed to start")
            sys.exit(1)
        candidates = load_candidates()
        by_id = {c["member"]["id"]: c for c in candidates}
        # a strong candidate, a sparse candidate, a candidate with failures
        for cid in ("CAND-001", "CAND-011", "CAND-010"):
            test_full_interview(by_id[cid], by_id[cid]["member"]["name"])
    finally:
        proc.terminate()
        try:
            proc.wait(timeout=10)
        except Exception:
            proc.kill()

    test_llm_path_and_fallback()
    test_empty_candidate_edge()

    print(f"\n===== {PASSED} passed, {FAILED} failed =====")
    sys.exit(1 if FAILED else 0)


if __name__ == "__main__":
    main()
