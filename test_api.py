PASSED = 0
FAILED = 0


def check(name: str, condition: bool, detail: str = "") -> None:
    global PASSED, FAILED
    if condition:
        PASSED += 1
        print(f"  [ok]   {name}")
    else:
        FAILED += 1
        print(f"  [FAIL] {name}  {detail}")


# ======================================================================
# Part 1 — planner compliance
# ======================================================================
def test_planner_compliance() -> None:
    print("\n[1] Planner compliance across all candidates")
    curriculum = load_curriculum()
    candidates = load_candidates()
    check(f"loaded {len(candidates)} candidates and {len(curriculum.get('days', []))} curriculum days",
          len(candidates) >= 15 and len(curriculum["days"]) >= 31)

    violations = verify_plan_for_all_candidates(curriculum, candidates)
    check("every candidate: >= 8 questions, >= 4 distinct days", not violations,
          f"violations: {violations}")

    # per-candidate detail + narrative sanity
    for c in candidates:
        profile = build_profile(c, curriculum)
        plan = build_plan(profile)
        stats = plan_stats(plan)
        opener = plan[0]
        check(
            f"{c['member']['id']} {c['member']['name']}: {stats['total_questions']} q / "
            f"{stats['distinct_days']} days / opens with Day {opener['day']}",
            stats["meets_min_questions"] and stats["meets_min_days"],
            json.dumps(stats),
        )


